class _PieLegend extends StatelessWidget {
  final Color color;
  final String label;
  final int count;
  final int total;

  const _PieLegend({required this.color, required this.label, required this.count, required this.total});

  @override
  Widget build(BuildContext context) {
    final pct = total == 0 ? 0.0 : (count / total) * 100;
    return Row(
      children: [
        Container(width: 10, height: 10, decoration: BoxDecoration(color: color, shape: BoxShape.circle)),
        const SizedBox(width: 8),
        Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(label, style: const TextStyle(color: HudyatColors.textPrimary, fontSize: 12, fontWeight: FontWeight.w600)),
            Text('$count  (${pct.toStringAsFixed(0)}%)',
                style: const TextStyle(color: HudyatColors.textSecondary, fontSize: 11)),
          ],
        ),
      ],
    );
  }
}

